DASH = u"—"          # —
NUM = re.compile(u"^(\\d+)\\.\\s+(.*)$")


def parse(src):
    cards, theme, nums = [], None, []
    for raw in src.split(u"\n"):
        line = raw.strip()
        if not line:
            continue
        m = NUM.match(line)
        if not m:
            raise SystemExit(u"ვერ გავიგე ხაზი: " + line)
        body = m.group(2)
        # ბარათია მხოლოდ მაშინ, თუ ტირეს წინ ინგლისური ტექსტია.
        # თემის სათაურში ტირე თუ იყოს (მაგ. „ყოველდღიური საუბარი — II"),
        # ლათინური ასო მის მარცხნივ არ გვხვდება — ასე ვასხვავებ.
        is_card = DASH in body and re.search(u"[a-zA-Z]", body.split(DASH, 1)[0])
        if not is_card:               # თემის სათაური
            theme = body.strip()
            continue
        en, ka = body.split(DASH, 1)
        cards.append({
            "en": en.strip(),
            "ka": ka.strip(),
            "src": theme,
            "n": int(m.group(1)),
        })
        nums.append(int(m.group(1)))
    return cards, nums


